#!/usr/bin/env node

const rawUrl = process.env.CITEM_COLLECTOR_URL?.trim();
const token = process.env.CITEM_COLLECTOR_TOKEN?.trim();
const once = process.env.CITEM_COLLECTOR_ONCE === "true";

if (!rawUrl) {
  console.error("CITEM_COLLECTOR_URL is required.");
  process.exit(2);
}
if (!token || !/^[a-f0-9]{64}$/.test(token)) {
  console.error("CITEM_COLLECTOR_TOKEN must be the 64-character token generated by TechINT → Technical Sources.");
  process.exit(2);
}

let baseUrl;
try {
  baseUrl = new URL(rawUrl);
} catch {
  console.error("CITEM_COLLECTOR_URL must be a valid URL.");
  process.exit(2);
}

const localHost = ["localhost", "127.0.0.1", "::1"].includes(baseUrl.hostname);
if (baseUrl.protocol !== "https:" && !(localHost && baseUrl.protocol === "http:")) {
  console.error("CITEM_COLLECTOR_URL must use HTTPS except for localhost development.");
  process.exit(2);
}

const endpoint = new URL("/api/techint/collector/tick", baseUrl);
let stopped = false;
let failureBackoffSeconds = 5;

process.on("SIGINT", () => { stopped = true; });
process.on("SIGTERM", () => { stopped = true; });

function sleep(seconds) {
  return new Promise((resolve) => setTimeout(resolve, Math.max(1, seconds) * 1000));
}

async function tick() {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 10 * 60 * 1000);
  try {
    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        authorization: `Bearer ${token}`,
        accept: "application/json",
        "user-agent": "CITEM-TechINT-Collector/2.3F-A-v1",
      },
      cache: "no-store",
      redirect: "error",
      signal: controller.signal,
    });

    if (response.status === 401) {
      throw Object.assign(new Error("Collector token was rejected. Rotate the token in CİTEM and update the local environment."), { fatal: true });
    }

    const payload = await response.json().catch(() => null);
    if (!response.ok || !payload || typeof payload !== "object") {
      throw new Error(`Collector endpoint returned HTTP ${response.status}.`);
    }

    if (payload.enabled === false) {
      console.log(`[${new Date().toISOString()}] continuous collection is paused on the server.`);
      return { stop: true, waitSeconds: Number(payload.waitSeconds ?? 60) };
    }

    const claimed = Number(payload.claimed ?? 0);
    const succeeded = Number(payload.succeeded ?? 0);
    const failed = Number(payload.failed ?? 0);
    const due = payload.due === true;
    console.log(
      `[${new Date().toISOString()}] ${due ? "tick" : "heartbeat"}: claimed=${claimed} succeeded=${succeeded} failed=${failed}`,
    );
    failureBackoffSeconds = 5;
    return { stop: false, waitSeconds: Math.max(5, Math.min(3600, Number(payload.waitSeconds ?? 60))) };
  } finally {
    clearTimeout(timeout);
  }
}

console.log(`CİTEM TechINT collector started for ${baseUrl.origin}.`);
console.log("Provider credentials and Supabase service-role credentials remain server-side.");

while (!stopped) {
  try {
    const result = await tick();
    if (once || result.stop) break;
    await sleep(result.waitSeconds);
  } catch (error) {
    if (error?.fatal) {
      console.error(error.message);
      process.exit(3);
    }
    const message = error?.name === "AbortError" ? "collector request timed out" : "collector endpoint unavailable";
    console.error(`[${new Date().toISOString()}] ${message}; retrying in ${failureBackoffSeconds}s.`);
    if (once) process.exit(4);
    await sleep(failureBackoffSeconds);
    failureBackoffSeconds = Math.min(60, failureBackoffSeconds * 2);
  }
}

console.log("CİTEM TechINT collector stopped.");
